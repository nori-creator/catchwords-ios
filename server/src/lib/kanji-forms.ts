/**
 * 上の表のうち、**台湾でも標準の字として使う物**（並且・月餅・岳父・芸香）。打った語が何語かの判定
 * （`text-query-lang.ts`）には今までどおり効かせるが、見出し語を落とす理由にはしない。
 */
const ALSO_TAIWAN_STANDARD = new Set("並餅岳芸");

/** 日本の新字体にしか無い字（台湾でも標準の字は除く）を含むか。 */
export function hasJapaneseOnlyKanji(text: string): boolean {
  for (const ch of text ?? "") if (JA_ONLY.has(ch) && !ALSO_TAIWAN_STANDARD.has(ch)) return true;
  return false;
}
