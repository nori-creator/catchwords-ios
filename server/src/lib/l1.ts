/**
 * 学習者の母語(L1)ごとの「つまずきポイント」辞書 — 台湾華語版。
 *
 * ## なぜ必要か
 * 台湾華語のどこで転ぶかは母語で全く違う。日本語話者は有気音/無気音の
 * 区別が無いので「ㄅとㄆが同じに聞こえる」が、韓国語話者は3系列の子音を
 * 持つので有気音は得意で、代わりに f(ㄈ) が無くて困る。ベトナム語話者は
 * 声調そのものは得意でも、自分の言語の6声調に引きずられる。
 *
 * この違いを AI のプロンプトに具体的に流し込むことで、「発音のコツ」も
 * 「添削の解説」も、その人の母語に本当に効く内容になる。
 * 抽象的に「母語に配慮して」と書くだけではモデルの解釈が揺れるので、
 * **音韻・文法の具体的な干渉項目を書き下す**のがこのファイルの役割。
 *
 * ## 構造の考え方(2026-07-29 改訂)
 * 以前は pronunciation / grammar の平文2つだった。これを節に分けたのは、
 * プロンプトに**必要な節だけ**を入れるため。発音のコツを作るのに文法の
 * 干渉項目まで送るとトークンが無駄になり、モデルの注意も散る。
 * `formatL1Rule(info, kind)` が用途に応じて節を選ぶ。
 *
 * ## priority を別に持つ理由
 * 項目を平らに並べると、モデルは「文字数の多い項目」や「最後に書いてある
 * 項目」に引っ張られる。実際に**通じなくなる順**を先に宣言しておくと、
 * 限られた2〜3文のアドバイスがちゃんと致命傷から埋まる。
 *
 * ## 2026-08-24: 学習言語ごとに分かれる場所を作った
 * この表は**台湾華語を学ぶときの**干渉項目。英語版では中身が丸ごと変わる
 * (日本語話者の英語の難所は声調ではなく冠詞・強勢・語末子音)。
 *
 * 見出しまで違う — 台湾華語は【量詞】が要るが、英語には量詞が無く、
 * 代わりに【冠詞・可算】が要る。そこで**整形の見出しを表に出して**、
 * 学習言語で引けるようにした(`RULE_LABELS`)。第4段で英語の欄を足すときに
 * 触るのはその表だけで、`formatL1Rule` の中身は触らない。
 *
 * **台湾華語の出力は1文字も変えていない。** `l1.test.ts` が
 * `__fixtures__/l1-prompts.zh-TW.json`(この変更の前に採った現物)と
 * 突き合わせて、12母語 × 4用途の48通りを全部見ている。
 *
 * ## 出典の考え方
 * 対照言語学で広く知られる母語干渉(L1 transfer)の項目を、台湾華語(注音)
 * の記号に対応づけて整理したもの。英語話者の第2声↔第3声の混同が、
 * F0(声の高さ)の転換点のタイミングに起因し、第二言語話者が転換点ではなく
 * 音の長さを手がかりにするために固定化するという知見は音声学の実験研究による。
 * 日本語話者の有気/無気の不区別も同様に確立した記述。台湾華語側の事実
 * (そり舌の浅さ・軽声の少なさ・兒化の不在)は台湾華語の記述研究による。
 */

