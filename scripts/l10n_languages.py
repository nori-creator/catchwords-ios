#!/usr/bin/env python3
"""The display-language registry: ios/Localization/languages.json → ios/Shared/DisplayLanguages.swift.

    python3 scripts/l10n_languages.py           # write the Swift file
    python3 scripts/l10n_languages.py --check   # CI: fail when the Swift file is not what the JSON makes

languages.json is the only list of display languages. The app (L10n, LanguageRules, ChunkRules, the widgets) reads
the generated Swift; check_l10n.py and add_language.py read the JSON through `load()` here.
"""
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
REGISTRY = os.path.join(ROOT, "ios", "Localization", "languages.json")
SWIFT = os.path.join(ROOT, "ios", "Shared", "DisplayLanguages.swift")
SCRIPTS = ("kana", "han", "hangul", "latin")
FIELDS = ("code", "autonym", "nameJa", "flag", "locale", "lproj", "devicePrefixes", "script", "listSeparator",
          "openBracket", "closeBracket", "placeSeparator", "glossLimit", "handwritingFont", "legalDocs", "reviewed",
          "plurals", "markerWords", "markerLetters", "degreeGlosses")


def load(path=REGISTRY):
    data = json.load(open(path, encoding="utf-8"))
    langs = data["languages"]
    codes = [l["code"] for l in langs]
    problems = []
    if len(set(codes)) != len(codes):
        problems.append("a language code is listed twice")
    for l in langs:
        missing = [f for f in FIELDS if f not in l]
        if missing:
            problems.append(f"{l.get('code', '?')}: missing {', '.join(missing)}")
        elif l["script"] not in SCRIPTS:
            problems.append(f"{l['code']}: script must be one of {', '.join(SCRIPTS)} (a new kind of script needs "
                            f"its own reader rules in LanguageRules.swift first)")
    for key in ("source", "fallback"):
        if data.get(key) not in codes:
            problems.append(f"{key} {data.get(key)!r} is not a listed language")
    if problems:
        sys.exit("languages.json: " + "; ".join(problems))
    return data


def targets(data):
    """The languages that need translations (every one but the source, whose text is the key itself)."""
    return [l for l in data["languages"] if l["code"] != data["source"]]


def swift_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def swift_list(items):
    return "[" + ", ".join(swift_str(i) for i in items) + "]"


def swift_dict(d):
    if not d:
        return "[:]"
    return "[" + ", ".join(f"{swift_str(k)}: {swift_str(v)}" for k, v in d.items()) + "]"


def unique_markers(data):
    """Per Latin-script language, the marker words and letters no other listed Latin-script language has, so a
    text's language can be told apart among them (they change as languages are added)."""
    latin = [l for l in data["languages"] if l["script"] == "latin"]
    out = {}
    for l in latin:
        others = [o for o in latin if o["code"] != l["code"]]
        words = [w for w in l["markerWords"] if not any(w in o["markerWords"] for o in others)]
        letters = "".join(c for c in l["markerLetters"] if not any(c in o["markerLetters"] for o in others))
        out[l["code"]] = (words, letters)
    return out


def render(data):
    markers = unique_markers(data)
    rows = []
    for l in data["languages"]:
        words, letters = markers.get(l["code"], ([], ""))
        rows.append(
            "        DisplayLanguage(\n"
            f"            code: {swift_str(l['code'])}, autonym: {swift_str(l['autonym'])}, nameJa: {swift_str(l['nameJa'])}, "
            f"flag: {swift_str(l['flag'])},\n"
            f"            localeID: {swift_str(l['locale'])}, lproj: {swift_str(l['lproj'])}, "
            f"devicePrefixes: {swift_list(l['devicePrefixes'])}, script: .{l['script']},\n"
            f"            listSeparator: {swift_str(l['listSeparator'])}, openBracket: {swift_str(l['openBracket'])}, "
            f"closeBracket: {swift_str(l['closeBracket'])}, placeSeparator: {swift_str(l['placeSeparator'])},\n"
            f"            glossLimit: {int(l['glossLimit'])}, handwritingFont: {str(bool(l['handwritingFont'])).lower()}, "
            f"legalDocs: {str(bool(l['legalDocs'])).lower()},\n"
            f"            plurals: {swift_dict(l['plurals'])},\n"
            f"            markerWords: {swift_list(words)},\n"
            f"            markerLetters: {swift_str(letters)},\n"
            f"            degreeGlosses: {swift_dict(l['degreeGlosses'])}\n"
            "        ),"
        )
    return (
        "// GENERATED by scripts/l10n_languages.py from ios/Localization/languages.json — do not edit by hand.\n"
        "// To add a display language: python3 scripts/add_language.py (docs/adding-a-display-language.md).\n"
        "import Foundation\n"
        "\n"
        "/// One display language: the screen's text, and the language the server writes explanations in.\n"
        "nonisolated struct DisplayLanguage: Sendable, Hashable {\n"
        "    /// Which reader rules apply (LanguageRules.looksWrong / readsAs): the script the language is written in.\n"
        "    enum Script: String, Sendable { case kana, han, hangul, latin }\n"
        "\n"
        "    /// `profiles.ui_language` and `explain_lang` (the web's codes).\n"
        "    let code: String\n"
        "    /// The language's name in itself (never translated).\n"
        "    let autonym: String\n"
        "    /// The language's name in Japanese: a key of strings.json, so `L10n.text(nameJa)` names it in the display language.\n"
        "    let nameJa: String\n"
        "    let flag: String\n"
        "    /// Dates and numbers.\n"
        "    let localeID: String\n"
        "    /// The Xcode localization folder (`<lproj>.lproj/InfoPlist.strings`).\n"
        "    let lproj: String\n"
        "    /// iPhone language ids (lowercased prefixes) that start the app in this language.\n"
        "    let devicePrefixes: [String]\n"
        "    let script: Script\n"
        "    /// Between spoken parts (、 / , / ，).\n"
        "    let listSeparator: String\n"
        "    let openBracket: String\n"
        "    let closeBracket: String\n"
        "    /// Between the parts of a place name (Taipei, Da'an / 台北 大安).\n"
        "    let placeSeparator: String\n"
        "    /// How many characters a short meaning keeps on a candidate card.\n"
        "    let glossLimit: Int\n"
        "    /// The bundled handwriting font has every letter of this language (else the system font is used).\n"
        "    let handwritingFont: Bool\n"
        "    /// The web has the terms and privacy policy in this language (else the English pages open).\n"
        "    let legalDocs: Bool\n"
        "    /// After the number 1: \"{1} words\" → \"{1} word\".\n"
        "    let plurals: [String: String]\n"
        "    /// Latin script: words and letters only this language has among the listed Latin-script languages.\n"
        "    let markerWords: Set<String>\n"
        "    let markerLetters: String\n"
        "    /// Mandarin degree words (很, 超 …) as they read in this language's chunk translations.\n"
        "    let degreeGlosses: [String: String]\n"
        "}\n"
        "\n"
        "nonisolated enum DisplayLanguages {\n"
        f"    /// The language the app is written in: its text is the key of every table.\n"
        f"    static let source = {swift_str(data['source'])}\n"
        f"    /// Shown when a translation is missing, and for an unknown code.\n"
        f"    static let fallback = {swift_str(data['fallback'])}\n"
        "\n"
        "    /// Every display language, in the order they are offered.\n"
        "    static let all: [DisplayLanguage] = [\n"
        + "\n".join(rows) + "\n"
        "    ]\n"
        "\n"
        "    static let codes: [String] = all.map(\\.code)\n"
        "\n"
        "    private static let byCode: [String: DisplayLanguage] = Dictionary(uniqueKeysWithValues: all.map { ($0.code, $0) })\n"
        "\n"
        "    static func find(_ code: String?) -> DisplayLanguage? { code.flatMap { byCode[$0] } }\n"
        "\n"
        "    /// A display language for any code: a listed code as it is, another by its language part (\"es-MX\" → es,\n"
        "    /// \"zh-Hant\" → zh-TW), else nil.\n"
        "    static func match(_ raw: String?) -> DisplayLanguage? {\n"
        "        let id = (raw ?? \"\").trimmingCharacters(in: .whitespaces)\n"
        "        if let exact = byCode[id] { return exact }\n"
        "        let base = id.lowercased().split(whereSeparator: { $0 == \"-\" || $0 == \"_\" }).first.map(String.init) ?? \"\"\n"
        "        guard !base.isEmpty else { return nil }\n"
        "        return all.first { $0.code.lowercased().split(separator: \"-\").first.map(String.init) == base }\n"
        "    }\n"
        "\n"
        "    /// The display language an iPhone language id (\"zh-Hant-TW\", \"es-419\") starts the app in, if any.\n"
        "    static func forDevice(_ id: String) -> DisplayLanguage? {\n"
        "        let l = id.lowercased().replacingOccurrences(of: \"_\", with: \"-\")\n"
        "        return all.first { $0.devicePrefixes.contains { p in l == p || l.hasPrefix(p + \"-\") } }\n"
        "    }\n"
        "}\n"
    )


def main():
    data = load()
    out = render(data)
    if "--check" in sys.argv:
        have = open(SWIFT, encoding="utf-8").read() if os.path.exists(SWIFT) else ""
        if have != out:
            sys.exit("ios/Shared/DisplayLanguages.swift is not what ios/Localization/languages.json makes: "
                     "run python3 scripts/l10n_languages.py and commit the result.")
        print(f"Display languages OK: {', '.join(l['code'] for l in data['languages'])}.")
        return
    open(SWIFT, "w", encoding="utf-8").write(out)
    print(f"wrote {os.path.relpath(SWIFT, ROOT)} ({len(data['languages'])} languages)")


if __name__ == "__main__":
    main()
